"""OpenPLC through its own Modbus master (a bridge config with an OpenPLC connection).

The OpenPLC runtime reaches canworks-bridge with the Modbus master the editor
configures from a remote device. This module makes, from a config and its
declarations (editorproject.declarations):

    devices/remote/<remote_device>.json   the editor's remote device: one
                                          Modbus TCP device at the bridge,
                                          read and write groups per range
    pous/programs/canworks_in.st          raw words -> the `canworks` list
    pous/programs/canworks_out.st         the `canworks` list -> raw words,
                                          then the PLC link header
    the `canworks` global variable list   typed values, `ok`, `link`

Every value goes through input registers (function 4) and holding registers
(function 16); each register gets one %IW or %QW from `iec_base` on. The raw
words are declared only inside the two programs, so a program sees names and
types. See the modbus-bridge-map and canopen-editor-project specs.
"""

