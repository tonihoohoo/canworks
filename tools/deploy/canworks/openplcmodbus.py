# What canworks last wrote into the project: {relative path: sha256}, so a
# file someone else changed is replaced only after a confirm.
STAMP = os.path.join("canworks", ".openplc-files.json")


class ChangedFiles(Exception):
    """Files canworks writes were changed by someone else since it wrote them."""

    def __init__(self, files):
        super().__init__("changed outside canworks: " + ", ".join(files))
        self.files = files


def own_files(cfg):
    """The project files canworks writes, relative, with /."""
    return ["devices/remote/%s.json" % settings(cfg)["remote_device"],
            "pous/programs/%s.st" % IN_PROGRAM, "pous/programs/%s.st" % OUT_PROGRAM]


def free_iec_base(cfg, decls, uses):
    """The lowest %IW/%QW index from 100 on where every point of the remote
    device fits without a location another part of the project uses (scan
    uses, canworks' own files left out)."""
    groups, _ = layout(cfg, decls, 0)
    n = {"I": sum(g.count for g in groups if g.area == "I"), "Q": sum(g.count for g in groups if g.area == "Q")}
    mine = set(own_files(cfg))
    taken = {(u.loc.area, u.loc.element) for u in uses
             if u.loc.size == "W" and u.loc.area in "IQ" and u.file not in mine}
    base = DEFAULT_IEC_BASE
    while any((a, base + k) in taken for a in "IQ" for k in range(n[a])):
        base += 1
    return base


def _sha(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def _stamps(project_dir):
    try:
        with open(os.path.join(project_dir, STAMP), encoding="utf-8") as f:
            doc = json.load(f)
        return doc if isinstance(doc, dict) else {}
    except (OSError, ValueError):
        return {}


def changed_files(project_dir, cfg, texts):
    """Own files that exist, are not what canworks last wrote there and are
    not what it would write now."""
    stamps = _stamps(project_dir)
    out = []
    for rel in own_files(cfg):
        path = os.path.join(project_dir, *rel.split("/"))
        if not os.path.isfile(path):
            continue
        sha = _sha(path)
        if sha != stamps.get(rel) and sha != hashlib.sha256(texts[rel].encode("utf-8")).hexdigest():
            out.append(rel)
    return out


def own_texts(cfg, decls, uses=()):
    """(%IW/%QW base, {own file: the text Save writes there})."""
    base = settings(cfg)["iec_base"]
    if base is None:
        base = free_iec_base(cfg, decls, uses)
    in_st, out_st = programs(cfg, decls, base)
    rel = own_files(cfg)
    return base, {rel[0]: remote_device_text(cfg, decls, base), rel[1]: in_st, rel[2]: out_st}


def _list_shape(lst):
    """A `canworks` list as [(name, type)], what the program sees of it; the
    editor may store the rest in its own way."""
    out = []
    for v in lst.get("variables") or []:
        t = v.get("type") if isinstance(v, dict) else None
        out.append((v.get("name"), t.get("value") if isinstance(t, dict) else None) if isinstance(v, dict) else None)
    return out


def outdated_files(project_dir, cfg, decls, uses=()):
    """What Save would write again although the config did not change: own
    files canworks wrote that are missing now or that it would now write
    differently (a newer canworks), and "project.json" when its `canworks`
    list differs from what Save writes or it does not enable the canworks
    library. Files someone else changed are left to
    changed_files."""
    stamps = _stamps(project_dir)
    if not stamps:
        return []  # canworks never wrote into this project: its first Save does
    _, texts = own_texts(cfg, decls, uses)
    out = []
    for rel in own_files(cfg):
        path = os.path.join(project_dir, *rel.split("/"))
        if rel not in stamps:
            continue
        if not os.path.isfile(path):
            out.append(rel)
            continue
        sha = _sha(path)
        if sha == stamps[rel] and sha != hashlib.sha256(texts[rel].encode("utf-8")).hexdigest():
            out.append(rel)
    try:
        with open(os.path.join(project_dir, "project.json"), encoding="utf-8") as f:
            data = json.load(f).get("data") or {}
    except (OSError, ValueError, AttributeError):
        return out
    lists = [l for l in data.get("globalVariableLists") or [] if isinstance(l, dict) and l.get("name") == LIST_NAME]
    libs = [l for l in data.get("libraries") or [] if isinstance(l, dict) and l.get("name") == plclibrary.NAME]
    # The library's version is not checked: Save installs this canworks'
    # library into the editor whatever the entry names.
    if [_list_shape(l) for l in lists] != [_list_shape(global_list(decls))] or not libs:
        out.append("project.json")
    return out


def sync_project(project_dir, cfg, decls, uses=(), force=False):
    """Writes the remote device, canworks_in, canworks_out and the list and
    instances in project.json with an OpenPLC connection. Raises ChangedFiles
    unless `force` when one of canworks' files was changed by someone else.
    Returns {written, iec_base, requests, warning}."""
    base, texts = own_texts(cfg, decls, uses)
    rel = own_files(cfg)
    changed = changed_files(project_dir, cfg, texts)
    if changed and not force:
        raise ChangedFiles(changed)
    written = []
    stamps = _stamps(project_dir)
    for r in rel:
        path = os.path.join(project_dir, *r.split("/"))
        os.makedirs(os.path.dirname(path), exist_ok=True)
        _write(path, texts[r])
        stamps[r] = hashlib.sha256(texts[r].encode("utf-8")).hexdigest()
        written.append(path)
    pj = os.path.join(project_dir, "project.json")
    with open(pj, encoding="utf-8") as f:
        doc = json.load(f)
    if not isinstance(doc, dict) or not isinstance(doc.get("data"), dict):
        raise OpenplcError("%s has no \"data\" object" % pj)
    doc["data"] = project_data(doc["data"], decls)
    _write(pj, json.dumps(doc, indent=2))
    written.append(pj)
    stamp = os.path.join(project_dir, STAMP)
    os.makedirs(os.path.dirname(stamp), exist_ok=True)
    _write(stamp, json.dumps(stamps, indent=2, sort_keys=True) + "\n")
    groups, _ = layout(cfg, decls, base)
    return {"written": written, "iec_base": base, "requests": request_count(groups),
            "warning": budget_warning(groups)}


def instances(resource):
    """`resource` (project.json data.configuration.resource) with canworks_in
    first and canworks_out last in the first task; returns the new instance
    list."""
    tasks = resource.get("tasks") or []
    task = tasks[0]["name"] if tasks and isinstance(tasks[0], dict) else None
    old = [i for i in resource.get("instances") or []
           if not (isinstance(i, dict) and i.get("program") in (IN_PROGRAM, OUT_PROGRAM))]
    mine = lambda program: {"name": program + "_instance", "task": task, "program": program}
    return [mine(IN_PROGRAM)] + old + [mine(OUT_PROGRAM)]


def project_data(data, decls):
    """project.json `data` with the canworks list and instances in place,
    and the canworks library enabled (canworks_in and canworks_out call its
    functions); an entry the project already has is kept."""
    data = dict(data)
    libs = [l for l in data.get("libraries") or [] if isinstance(l, dict)]
    if not any(l.get("name") == plclibrary.NAME for l in libs):
        data["libraries"] = libs + [{"name": plclibrary.NAME, "version": plclibrary.__version__}]
    lists = [l for l in data.get("globalVariableLists") or []
             if not (isinstance(l, dict) and l.get("name") == LIST_NAME)]
    data["globalVariableLists"] = lists + [global_list(decls)]
    conf = dict(data.get("configuration") or {})
    resource = dict(conf.get("resource") or {})
    resource["instances"] = instances(resource)
    conf["resource"] = resource
    data["configuration"] = conf
    return data


def _write(path, text):
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    replace_file(tmp, path)
