IN_PROGRAM = "canworks_in"
OUT_PROGRAM = "canworks_out"
LIST_NAME = "canworks"
# `canworks.link`, the blocks' LINK: one word per bridge register. Words 0-3
# status, 4-6 control, 7-13 SDO request, 14-20 SDO response, 21 flags (bit 0
# ok, 1 control block, 2 SDO registers, 8 + n live list of network n), 22-24
# the blocks' own (owners, instance numbers), 25 + 8n the live list of
# network n. The mailboxes (modbus-bridge-mailboxes): 89 their flags (bits
# 0-2 request mailboxes, 4 receive, 5 network info, 8-12 cyclic jobs), 90-101
# the blocks' own (turns, owners), 102-104 the receive acknowledgement, 105
# the blocks' own, 128 + j the keepalive of cyclic job j, 144 + 144m request
# mailbox m (72 request words, then 72 response words), 720 the receive
# mailbox (120 words per receive block, 2 at most), 960 + 18n the info of
# network n, 1104 the cyclic job table. A plain
# word array: STruC++ 0.7.0 emits a project's structs before a library's, so
# a library STRUCT cannot be a list member.
LINK_WORDS = 1280
LINK_STATUS, LINK_CTL, LINK_SDO_REQ, LINK_SDO_RSP, LINK_FLAGS, LINK_LIVE = 0, 4, 7, 14, 21, 25
LINK_MB_FLAGS, LINK_ACK, LINK_KEEPALIVE, LINK_MAILBOX, LINK_RECEIVE, LINK_INFO, LINK_CYCLIC = (
    89, 102, 128, 144, 720, 960, 1104)
LINK_RECEIVE_WORDS = 120
LINK_MAILBOX_WORDS = 144
LINK_INFO_WORDS = 18
DEFAULT_IEC_BASE = 100
HOST = "127.0.0.1"
TIMEOUT_MS = 1000
REQUEST_BUDGET = 40
LINK_LIVE_WORDS = 8
LINK_NETWORKS = 8
STATUS_COUNTER_WORD = 1  # status bytes 2-3: grows every 100 ms
GENERATED = "(* Generated by canworks from canworks/canworks.json: do not edit, Update declarations rewrites it. *)"
GENERATED_OTHER = "(* Generated by canworks: do not edit, export the map again after a config change. *)"

_FC_TYPE = {"4": "Analog Input (Input Register)", "16": "Analog Output (Multiple Registers)"}
_NS = uuid.UUID("6f1c3a52-6e0b-4c1e-9a52-63616e776f72")


class OpenplcError(ValueError):
    pass


def settings(cfg):
    """bridgecheck.link_settings (openplc_settings with an OpenPLC connection)
    plus the unit id."""
    out = bridgecheck.link_settings(cfg)
    unit = cfg["bridge"].get("unit_id", 1)
    out["unit_id"] = unit if isinstance(unit, int) and not isinstance(unit, bool) else 1
    return out


# -- Register layout ---------------------------------------------------------

class Group:
    """One I/O group of the remote device: `area` "I" (function 4) or "Q"
    (function 16), registers `first`..`first + count - 1`, the %IW/%QW index
    of its first point, and the alias of each point."""

    def __init__(self, area, key, first, label):
        self.area = area
        self.key = key
        self.first = first
        self.count = 0
        self.label = label
        self.iec_first = None
        self.aliases = []

    @property
    def fc(self):
        return "4" if self.area == "I" else "16"

    @property
    def registers(self):
        return range(self.first, self.first + self.count)


def _class(it):
    """Registers of one class may share a group: the PLC link header writes
    alone; the bridge's input blocks read with set-to-zero (a lost bridge
    reads as hash 0, so `canworks.ok` drops at once); data reads keep their
    last value."""
    if it.name == "bridge.plc_link":
        return "header"
    if it.kind == "bridge" and it.loc.area == "I":
        return "bridge"
    return "data"


def _units(items, area):
    """[(first register, count, class)]: the register ranges of the values of
    `area`, merged where values share a register, in register order. A group
    is cut only between units, so a value never spans two requests."""
    spans = sorted(((it.loc.index // 2, (it.loc.index + it.nbytes + 1) // 2, _class(it))
                    for it in items if it.loc.area == area))
    units = []
    for first, end, cls in spans:
        if units and first < units[-1][1]:
            u = units[-1]
            units[-1] = (u[0], max(u[1], end), u[2])
        else:
            units.append((first, end, cls))
    return [(first, end - first, cls) for first, end, cls in units]


def layout(cfg, decls, iec_base=None):
    """(groups, {(area, register): "%IWn"/"%QWn"}) with an OpenPLC connection: in
    file order, the header write group first, then the read groups, then the
    other write groups. Contiguous registers of one class share a group up to
    125 (read) or 123 (write) registers."""
    if not modbusmap.is_openplc(cfg):
        raise OpenplcError("the config has no OpenPLC connection (bridge.connections)")
    items = modbusmap.collect(cfg)
    problems = modbusmap.check(items)
    if problems:
        raise OpenplcError("; ".join(problems))
    base = DEFAULT_IEC_BASE if iec_base is None else iec_base
    names = _register_names(cfg, items, decls)
    groups = []
    for area, limit in (("I", modbusmap.MAX_READ_REGISTERS), ("Q", modbusmap.MAX_WRITE_REGISTERS)):
        current = None
        for first, count, cls in _units(items, area):
            if (current is None or first != current.first + current.count or cls != current.key
                    or current.count + count > limit):
                current = Group(area, cls, first, cls)
                groups.append(current)
            current.count += count
            # A value longer than one request (a long trouble code list) is cut.
            while current.count > limit:
                rest = current.count - limit
                current.count = limit
                current = Group(area, cls, current.first + limit, cls)
                current.count = rest
                groups.append(current)
    for g in groups:
        g.aliases = [names.get((g.area, reg), "") for reg in g.registers]
    header = [g for g in groups if g.key == "header"]
    ordered = header + [g for g in groups if g.area == "I"] + [g for g in groups if g.area == "Q" and g.key != "header"]
    where = {}
    nxt = {"I": base, "Q": base}
    for g in sorted(ordered, key=lambda g: (g.area, g.first)):
        g.iec_first = nxt[g.area]
        for k, reg in enumerate(g.registers):
            where[(g.area, reg)] = "%%%sW%d" % (g.area, g.iec_first + k)
        nxt[g.area] += g.count
    return ordered, where


def _register_names(cfg, items, decls):
    """{(area, register): alias}: the value a register carries, `<value>_w<n>`
    for later words of a wider value, the bridge block's name for its words."""
    names = {}
    for d in decls:
        loc = parse_location(d.get("location"))
        if loc is None:
            continue
        nbytes = 1 if loc.size == "X" else modbusmap.SIZE_BYTES[loc.size]
        first = loc.index // 2
        for k, reg in enumerate(range(first, (loc.index + nbytes + 1) // 2)):
            names.setdefault((loc.area, reg), d["name"] if k == 0 else "%s_w%d" % (d["name"], k))
    for it in items:
        if it.kind != "bridge":
            continue
        base = "cw_" + declare.identifier(it.name[len("bridge."):] if it.name.startswith("bridge.") else it.name)
        for k, reg in enumerate(range(it.loc.index // 2, (it.loc.index + it.nbytes + 1) // 2)):
            names.setdefault((it.loc.area, reg), base if k == 0 else "%s_w%d" % (base, k))
    return names


def request_count(groups):
    """Modbus requests per poll: one per group."""
    return len(groups)


def budget_warning(groups):
    n = request_count(groups)
    if n > REQUEST_BUDGET:
        return ("%d Modbus requests per poll (more than %d): the runtime's Modbus master may not keep up; "
                "pack the config (Pack for Modbus) or raise poll_ms" % (n, REQUEST_BUDGET))
    return None


# -- Remote device file --------------------------------------------------------

def remote_device(cfg, decls, iec_base=None):
    """The editor's remote device (devices/remote/<name>.json) as a dict."""
    s = settings(cfg)
    groups, _ = layout(cfg, decls, iec_base)
    io_groups = []
    for g in groups:
        name = "%s_%s_%d" % ("in" if g.area == "I" else "out", g.label, g.first)
        io_groups.append({
            "id": str(uuid.uuid5(_NS, "%s/%s" % (s["remote_device"], name))),
            "name": name,
            "functionCode": g.fc,
            "cycleTime": s["poll_ms"],
            "offset": str(g.first),
            "length": g.count,
            "errorHandling": "set-to-zero" if g.key in ("header", "bridge") and g.area == "I" else "keep-last-value",
            "ioPoints": [{
                "id": "%s_%d" % (name, k),
                "name": "%s_%d" % (name, k),
                "type": _FC_TYPE[g.fc],
                "iecLocation": "%%%sW%d" % (g.area, g.iec_first + k),
                "alias": alias,
            } for k, alias in enumerate(g.aliases)],
        })
    return {
        "name": s["remote_device"],
        "protocol": "modbus-tcp",
        "modbusTcpConfig": {
            "transport": "tcp",
            "host": HOST,
            "port": s["port"],
            "timeout": TIMEOUT_MS,
            "slaveId": s["unit_id"],
            "ioGroups": io_groups,
        },
    }


def remote_device_text(cfg, decls, iec_base=None):
    return json.dumps(remote_device(cfg, decls, iec_base), indent=2) + "\n"


def remote_device_path(project_dir, cfg):
    return os.path.join(project_dir, REMOTE_DIR, settings(cfg)["remote_device"] + ".json")


# -- Generated programs ----------------------------------------------------------

_IEC_SIZE = {"BOOL": "X", "SINT": "B", "USINT": "B", "BYTE": "B", "INT": "W", "UINT": "W", "WORD": "W",
             "DINT": "D", "UDINT": "D", "DWORD": "D", "REAL": "D", "LINT": "L", "ULINT": "L", "LWORD": "L",
             "LREAL": "L"}


def _raw(area, reg):
    return "%s%d" % ("i" if area == "I" else "q", reg)


def _hex(v):
    """A WORD literal: typed, as strict IEC checkers (CODESYS, truST) want."""
    return "WORD#16#%04X" % v


def _in_expr(d, loc, iec, raw=_raw):
    """ST expression of a declaration's value from the raw input words."""
    t = d["type"]
    reg = loc.index // 2
    w = raw("I", reg)
    if loc.size == "X":
        bit = loc.bit + (8 if loc.index % 2 == 0 else 0)
        return "(%s AND %s) <> WORD#0" % (w, _hex(1 << bit))
    if loc.size == "B":
        byte = "SHR(%s, 8)" % w if loc.index % 2 == 0 else "(%s AND WORD#16#00FF)" % w
        return byte if t == "WORD" else "WORD_TO_%s(%s)" % (t, byte)
    if loc.size == "W":
        return w if t == "WORD" else "WORD_TO_%s(%s)" % (t, w)
    words = [raw("I", reg + k) for k in range(2 if loc.size == "D" else 4)]
    if iec == "high_first":
        words.reverse()
    if loc.size == "D":
        dw = "(SHL(WORD_TO_DWORD(%s), 16) OR WORD_TO_DWORD(%s))" % (words[1], words[0])
        return {"DWORD": dw, "REAL": "CW_DWORD_TO_REAL(%s)" % dw}.get(t, "DWORD_TO_%s(%s)" % (t, dw))
    lw = " OR ".join("SHL(WORD_TO_LWORD(%s), %d)" % (words[k], 16 * k) if k else "WORD_TO_LWORD(%s)" % words[k]
                     for k in range(4))
    lw = "(%s)" % lw
    return {"LWORD": lw, "LREAL": "CW_LWORD_TO_LREAL(%s)" % lw}.get(t, "LWORD_TO_%s(%s)" % (t, lw))


def _out_parts(d, loc, iec, temps):
    """[(register, ST word expression)] of a declaration's output value. A
    32- or 64-bit value is converted once into a temporary (`temps` gets
    (name, type, expression))."""
    t = d["type"]
    v = "%s.%s" % (LIST_NAME, d["name"])
    reg = loc.index // 2
    high = loc.index % 2 == 0
    if loc.size == "X":
        bit = loc.bit + (8 if high else 0)
        # SEL, not BOOL_TO_WORD: truST has no BOOL to WORD conversion.
        return [(reg, "SEL(%s, WORD#0, %s)" % (v, _hex(1 << bit)))]
    if loc.size == "B":
        word = v if t == "WORD" else "%s_TO_WORD(%s)" % (t, v)
        word = "(%s AND WORD#16#00FF)" % word
        return [(reg, "SHL(%s, 8)" % word if high else word)]
    if loc.size == "W":
        return [(reg, v if t == "WORD" else "%s_TO_WORD(%s)" % (t, v))]
    n = 2 if loc.size == "D" else 4
    if loc.size == "D":
        whole = {"DWORD": v, "REAL": "CW_REAL_TO_DWORD(%s)" % v}.get(t, "%s_TO_DWORD(%s)" % (t, v))
        temp, to_word = "d%d" % reg, "DWORD_TO_WORD"
        temps.append((temp, "DWORD", whole))
    else:
        whole = {"LWORD": v, "LREAL": "CW_LREAL_TO_LWORD(%s)" % v}.get(t, "%s_TO_LWORD(%s)" % (t, v))
        temp, to_word = "l%d" % reg, "LWORD_TO_WORD"
        temps.append((temp, "LWORD", whole))
    parts = []
    for k in range(n):
        word = "%s(SHR(%s, %d))" % (to_word, temp, 16 * k) if k else "%s(%s)" % (to_word, temp)
        pos = k if iec == "low_first" else n - 1 - k
        parts.append((reg + pos, word))
    return parts


def _typed(decls):
    """The declarations the list carries: located, with a type the
    conversion knows, unique names."""
    out = []
    seen = {"ok", "link", "in_w", "out_w"}
    for d in decls:
        loc = parse_location(d.get("location"))
        if loc is None or loc.area not in "IQ" or _IEC_SIZE.get(d.get("type")) is None:
            continue
        if _IEC_SIZE[d["type"]] != loc.size and not (loc.size == "B" and d["type"] == "WORD"):
            continue
        if d["name"].lower() in seen:
            continue
        seen.add(d["name"].lower())
        out.append((d, loc))
    return out


def _block_starts(cfg):
    """{block name: (first register, word count)} of the bridge's blocks, and
    the live lists as [(network index, first register)]."""
    b = cfg["bridge"]
    out = {}
    for key, name, nbytes in (("control_location", "ctl", 6),):
        loc = parse_location(b.get(key))
        if loc is not None:
            out[name] = loc.index // 2
    sdo = b.get("sdo_bridge_location")
    if isinstance(sdo, dict):
        for key, name in (("request", "sdo_req"), ("response", "sdo_rsp")):
            loc = parse_location(sdo.get(key))
            if loc is not None:
                out[name] = loc.index // 2
    # A network without a name goes by its interface's, as in the bridge.
    nets = {n["name"]: n["index"] for n in contract.networks(cfg) if n["name"]}
    live = []
    for entry in b.get("live_lists") or []:
        loc = parse_location(entry.get("location")) if isinstance(entry, dict) else None
        if loc is not None and entry.get("network") in nets:
            live.append((nets[entry["network"]], loc.index // 2))
    return out, live


def _mailbox_copies(cfg):
    """[(area, first register, LINK word, words)] of the mailbox blocks, and
    the LINK flags word of the mailboxes (0 without them)."""
    mb = cfg["bridge"].get("mailboxes")
    if not isinstance(mb, dict):
        return [], 0
    base = {"I": parse_location(mb.get("input_location")), "Q": parse_location(mb.get("output_location"))}
    if base["I"] is None or base["Q"] is None:
        return [], 0
    networks = len(cfg.get("networks") or [])
    n = mailboxlayout.settings(mb, networks)
    flags = n["requests"] | (0x10 if n["receive"] else 0) | (0x20 if n["info_networks"] else 0) | (n["cyclic_jobs"] << 8)
    out = []
    for area, offset, nbytes, name, _ in mailboxlayout.blocks(mb, networks):
        part = name.split(".")[2:]
        if part[0] == "receive":
            word = LINK_RECEIVE + LINK_RECEIVE_WORDS * int(part[1])
        elif part[0] == "receive_ack":
            word = LINK_ACK
        elif part[0] == "network_info":
            word = LINK_INFO + LINK_INFO_WORDS * int(part[1])
        elif part[0] == "cyclic_jobs":
            word = LINK_CYCLIC
        elif part[0] == "keepalives":
            word = LINK_KEEPALIVE
        else:
            word = LINK_MAILBOX + LINK_MAILBOX_WORDS * int(part[0]) + (72 if part[1] == "response" else 0)
        out.append((area, (base[area].index + offset) // 2, word, nbytes // 2))
    return out, flags


def _raw_block(area, where, regs, notes):
    decls = [{"name": _raw(area, r), "type": "WORD", "location": where[(area, r)],
              "description": notes.get(r, "")} for r in regs]
    return declare.editor_block(decls)


def _used_registers(cfg):
    """{(area, register)} of every located value and block of a config."""
    items = modbusmap.collect(cfg)
    problems = modbusmap.check(items)
    if problems:
        raise OpenplcError("; ".join(problems))
    used = set()
    for it in items:
        for reg in range(it.loc.index // 2, (it.loc.index + it.nbytes + 1) // 2):
            used.add((it.loc.area, reg))
    return used


def channel_sizes(cfg):
    """{"I": n, "Q": n}: the length of canworks.in_w and canworks.out_w, up
    to the last used input and holding register."""
    used = _used_registers(cfg)
    return {a: max([r for (x, r) in used if x == a] or [0]) + 1 for a in "IQ"}


def _channel_word(area, reg):
    return "%s.%s[%d]" % (LIST_NAME, "in_w" if area == "I" else "out_w", reg)


def programs(cfg, decls, iec_base=None, other=False):
    """(canworks_in.st, canworks_out.st) texts in the editor's program form,
    or with `other` for another Modbus PLC: the raw words are then
    canworks.in_w and canworks.out_w, the channel variables, instead of
    %IW/%QW locals."""
    s = settings(cfg)
    if other:
        if not modbusmap.has_plc_link(cfg):
            raise OpenplcError("not a PLC link config: turn on the bridge's PLC link (\"plc_link\": true) and "
                               "run Pack for Modbus")
        groups, where, raw = [], dict.fromkeys(_used_registers(cfg)), _channel_word
    else:
        groups, where = layout(cfg, decls, iec_base)
        raw = _raw
    iec = modbusmap.word_order_of(cfg)
    h = modbusmap.map_hash(cfg)
    typed = _typed(decls)
    blocks, live = _block_starts(cfg)
    copies, mb_flags = _mailbox_copies(cfg)
    in_regs = sorted(r for (a, r) in where if a == "I")
    out_regs = sorted(r for (a, r) in where if a == "Q")
    names = {}
    for g in groups:
        for reg, alias in zip(g.registers, g.aliases):
            names[(g.area, reg)] = alias
    stale_ms = max(300, 3 * s["watchdog_ms"])

    body = [GENERATED_OTHER if other else GENERATED]
    body.append("moved := %s <> last_counter;" % raw("I", 2 + STATUS_COUNTER_WORD))
    body.append("last_counter := %s;" % raw("I", 2 + STATUS_COUNTER_WORD))
    body.append("stale(IN := NOT moved, PT := T#%dms);" % stale_ms)
    body.append("%s.ok := %s = %s AND %s = %s AND NOT stale.Q;"
                % (LIST_NAME, raw("I", 0), _hex(h >> 16), raw("I", 1), _hex(h & 0xFFFF)))
    flags = (2 if "ctl" in blocks else 0) | (4 if "sdo_req" in blocks and "sdo_rsp" in blocks else 0)
    for net, _ in live:
        if net < LINK_NETWORKS:
            flags |= 1 << (8 + net)
    body.append("%s.link[%d] := %s OR SEL(%s.ok, WORD#0, WORD#1);" % (LIST_NAME, LINK_FLAGS, _hex(flags), LIST_NAME))
    for k in range(4):
        body.append("%s.link[%d] := %s;" % (LIST_NAME, LINK_STATUS + k, raw("I", 2 + k)))
    if "sdo_rsp" in blocks:
        for k in range(7):
            body.append("%s.link[%d] := %s;" % (LIST_NAME, LINK_SDO_RSP + k, raw("I", blocks["sdo_rsp"] + k)))
    for net, first in live:
        if net >= LINK_NETWORKS:
            continue
        for k in range(LINK_LIVE_WORDS):
            body.append("%s.link[%d] := %s;" % (LIST_NAME, LINK_LIVE + net * LINK_LIVE_WORDS + k,
                                                raw("I", first + k)))
    if mb_flags:
        body.append("%s.link[%d] := %s;" % (LIST_NAME, LINK_MB_FLAGS, _hex(mb_flags)))
    for area, first, word, count in copies:
        if area == "I":
            for k in range(count):
                body.append("%s.link[%d] := %s;" % (LIST_NAME, word + k, raw("I", first + k)))
    if mb_flags:
        body.append("link_service(LINK := %s.link);" % LIST_NAME)
    for d, loc in typed:
        if loc.area == "I":
            body.append("%s.%s := %s;" % (LIST_NAME, d["name"], _in_expr(d, loc, iec, raw)))
    locals_ = [{"name": "last_counter", "type": "WORD"}, {"name": "moved", "type": "BOOL"},
               {"name": "stale", "type": "TON"}]
    if mb_flags:
        locals_.append({"name": "link_service", "type": "CW_LINK_SERVICE"})
    in_vars = declare.editor_block(locals_)
    if not other:
        in_vars = _raw_block("I", where, in_regs, {r: names.get(("I", r), "") for r in in_regs}) + "\n" + in_vars
    in_st = "PROGRAM %s\n%s\n\n%s\n\nEND_PROGRAM" % (IN_PROGRAM, in_vars, "\n".join(body))

    parts = {}
    temps = []
    for d, loc in typed:
        if loc.area == "Q":
            for reg, expr in _out_parts(d, loc, iec, temps):
                parts.setdefault(reg, []).append(expr)
    if "ctl" in blocks:
        for k in range(3):
            parts.setdefault(blocks["ctl"] + k, []).append("%s.link[%d]" % (LIST_NAME, LINK_CTL + k))
    if "sdo_req" in blocks:
        for k in range(7):
            parts.setdefault(blocks["sdo_req"] + k, []).append("%s.link[%d]" % (LIST_NAME, LINK_SDO_REQ + k))
    for area, first, word, count in copies:
        if area == "Q":
            for k in range(count):
                parts.setdefault(first + k, []).append("%s.link[%d]" % (LIST_NAME, word + k))
    body = [GENERATED_OTHER if other else GENERATED]
    body += ["%s := %s;" % (name, expr) for name, _, expr in temps]
    for reg in out_regs:
        if reg < 3:
            continue
        exprs = parts.get(reg) or ["WORD#0"]
        body.append("%s := %s;" % (raw("Q", reg), " OR ".join(exprs)))
    body.append("(* PLC link header, last: running, then the map hash 0x%08x *)" % h)
    body.append("%s := %s;" % (raw("Q", 1), _hex(h >> 16)))
    body.append("%s := %s;" % (raw("Q", 2), _hex(h & 0xFFFF)))
    body.append("%s := WORD#1;" % raw("Q", 0))
    out_vars = [] if other else [_raw_block("Q", where, out_regs, {r: names.get(("Q", r), "") for r in out_regs})]
    if temps:
        out_vars.append(declare.editor_block([{"name": name, "type": type_} for name, type_, _ in temps]))
    out_vars = "\n".join(out_vars)
    out_st = "PROGRAM %s\n%s\n%s\n\nEND_PROGRAM" % (OUT_PROGRAM, out_vars + "\n" if out_vars else "", "\n".join(body))
    return in_st, out_st


def global_list(decls):
    """The `canworks` global variable list in project.json's form."""
    def var(name, type_, doc):
        return {"name": name, "class": "global", "type": {"definition": "base-type", "value": type_},
                "location": "", "documentation": doc}
    link = {"name": "link", "class": "global",
            "type": {"definition": "array", "value": "ARRAY[0..%d] OF WORD" % (LINK_WORDS - 1),
                     "data": {"baseType": {"definition": "base-type", "value": "WORD"},
                              "dimensions": [{"dimension": "0..%d" % (LINK_WORDS - 1)}]}},
            "location": "", "documentation": "the bridge's control, SDO, live list and mailbox words: the canworks blocks' LINK"}
    variables = [var("ok", "BOOL", "canworks-bridge answers and serves this program's map"), link]
    for d, loc in _typed(decls):
        variables.append(var(d["name"], d["type"], declare.comment_text(d.get("description") or "")))
    return {"name": LIST_NAME, "variables": variables,
            "documentation": "canworks values; generated, Update declarations rewrites it"}


def other_plc_st(cfg, decls):
    """The ST file `--export-modbus-map OUT.st` writes for a PLC link config:
    for a Modbus PLC other than OpenPLC, the `canworks` list with the
    channel variables `in_w` and `out_w`, the client channels to map onto
    them, and canworks_in and canworks_out (modbus-bridge-map spec)."""
    in_st, out_st = programs(cfg, decls, other=True)
    last = {a: n - 1 for a, n in channel_sizes(cfg).items()}
    rows = modbusmap.register_map(cfg)
    lines = ["(* canworks PLC link for a Modbus PLC: the bridge's Modbus TCP port %d, unit %d, word order %s, map hash"
             % (settings(cfg)["port"], settings(cfg)["unit_id"], modbusmap.word_order_of(cfg)),
             "   16#%08X." % modbusmap.map_hash(cfg),
             "   1. Save the VAR_GLOBAL block as a global variable list named %s." % LIST_NAME,
             "   2. Create the Modbus TCP client channels below on the PLC, mapped onto %s.in_w and %s.out_w,"
             % (LIST_NAME, LIST_NAME),
             "      at a cycle well below the bridge's watchdog.",
             "   3. Add the canworks library sources (canworks-deploy library --format st --out DIR).",
             "   4. Run canworks_in first and canworks_out last in every scan of the task that uses the values",
             "      and the blocks (LINK := %s.link). *)"
             % LIST_NAME,
             "VAR_GLOBAL"]
    lst = global_list(decls)
    for v in lst["variables"]:
        lines.append("  %s : %s;%s" % (v["name"], v["type"]["value"],
                                       " (* %s *)" % v["documentation"] if v["documentation"] else ""))
        if v["name"] == "link":
            lines.append("  in_w : ARRAY[0..%d] OF WORD; (* input registers 0..%d, read with function 4 *)"
                         % (last["I"], last["I"]))
            lines.append("  out_w : ARRAY[0..%d] OF WORD; (* holding registers 0..%d, written with function 16 *)"
                         % (last["Q"], last["Q"]))
    lines.append("END_VAR")
    lines.append("")
    lines.append("(* Client channels:")
    for f, start, count, d in modbusmap.suggest_channels(rows):
        lines.append("   function %-2d registers %d..%d -> %s.%s[%d..%d]"
                     % (f, start, start + count - 1, LIST_NAME, "in_w" if d == "input" else "out_w",
                        start, start + count - 1))
    lines.append("*)")
    return "\n".join(lines) + "\n\n" + in_st + "\n\n" + out_st + "\n"


