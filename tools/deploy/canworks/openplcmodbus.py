"""OpenPLC through its own Modbus master (a bridge config with `bridge.openplc`).

The OpenPLC runtime reaches canworks-bridge with the Modbus master the editor
configures from a remote device. This module makes, from a config and its
declarations (editorproject.declarations):

    devices/remote/<remote_device>.json   the editor's remote device: one
                                          Modbus TCP device at the bridge,
                                          read and write groups per range
    pous/programs/canworks_in.st          raw words -> the `canworks` list
    pous/programs/canworks_out.st         the `canworks` list -> raw words,
                                          then the PLC link header
    the `canworks` global variable list   typed values, `ok`, `link`

Every value goes through input registers (function 4) and holding registers
(function 16); each register gets one %IW or %QW from `iec_base` on. The raw
words are declared only inside the two programs, so a program sees names and
types. See the modbus-bridge-map and canopen-editor-project specs.
"""

import hashlib
import json
import os
import uuid

from . import bridgecheck, modbusmap
from .configurator import declare
from .iec import parse_location
from .userdirs import replace_file

REMOTE_DIR = os.path.join("devices", "remote")
PROGRAMS_DIR = os.path.join("pous", "programs")
IN_PROGRAM = "canworks_in"
OUT_PROGRAM = "canworks_out"
LIST_NAME = "canworks"
# `canworks.link`, the blocks' LINK: one word per bridge register. Words 0-3
# status, 4-6 control, 7-13 SDO request, 14-20 SDO response, 21 flags (bit 0
# ok, 1 control block, 2 SDO registers, 8 + n live list of network n), 22-24
# the blocks' own (owners, instance numbers), 25 + 8n the live list of
# network n. A plain word array: STruC++ 0.7.0 emits a project's structs
# before a library's, so a library STRUCT cannot be a list member.
LINK_WORDS = 89
LINK_STATUS, LINK_CTL, LINK_SDO_REQ, LINK_SDO_RSP, LINK_FLAGS, LINK_LIVE = 0, 4, 7, 14, 21, 25
DEFAULT_IEC_BASE = 100
HOST = "127.0.0.1"
TIMEOUT_MS = 1000
REQUEST_BUDGET = 40
LINK_LIVE_WORDS = 8
LINK_NETWORKS = 8
STATUS_COUNTER_WORD = 1  # status bytes 2-3: grows every 100 ms
GENERATED = "(* Generated by canworks from canworks/canworks.json: do not edit, Update declarations rewrites it. *)"

_FC_TYPE = {"4": "Analog Input (Input Register)", "16": "Analog Output (Multiple Registers)"}
_NS = uuid.UUID("6f1c3a52-6e0b-4c1e-9a52-63616e776f72")


class OpenplcError(ValueError):
    pass


def settings(cfg):
    """bridgecheck.openplc_settings plus the unit id."""
    out = bridgecheck.openplc_settings(cfg)
    unit = cfg["bridge"].get("unit_id", 1)
    out["unit_id"] = unit if isinstance(unit, int) and not isinstance(unit, bool) else 1
    return out


# -- Register layout ---------------------------------------------------------

class Group:
    """One I/O group of the remote device: `area` "I" (function 4) or "Q"
    (function 16), registers `first`..`first + count - 1`, the %IW/%QW index
    of its first point, and the alias of each point."""

    def __init__(self, area, key, first, label):
        self.area = area
        self.key = key
        self.first = first
        self.count = 0
        self.label = label
        self.iec_first = None
        self.aliases = []

    @property
    def fc(self):
        return "4" if self.area == "I" else "16"

    @property
    def registers(self):
        return range(self.first, self.first + self.count)


def _class(it):
    """Registers of one class may share a group: the PLC link header writes
    alone; the bridge's input blocks read with set-to-zero (a lost bridge
    reads as hash 0, so `canworks.ok` drops at once); data reads keep their
    last value."""
    if it.name == "bridge.plc_link":
        return "header"
    if it.kind == "bridge" and it.loc.area == "I":
        return "bridge"
    return "data"


def _units(items, area):
    """[(first register, count, class)]: the register ranges of the values of
    `area`, merged where values share a register, in register order. A group
    is cut only between units, so a value never spans two requests."""
    spans = sorted(((it.loc.index // 2, (it.loc.index + it.nbytes + 1) // 2, _class(it))
                    for it in items if it.loc.area == area))
    units = []
    for first, end, cls in spans:
        if units and first < units[-1][1]:
            u = units[-1]
            units[-1] = (u[0], max(u[1], end), u[2])
        else:
            units.append((first, end, cls))
    return [(first, end - first, cls) for first, end, cls in units]


def layout(cfg, decls, iec_base=None):
    """(groups, {(area, register): "%IWn"/"%QWn"}) of an openplc config: in
    file order, the header write group first, then the read groups, then the
    other write groups. Contiguous registers of one class share a group up to
    125 (read) or 123 (write) registers."""
    if not modbusmap.is_openplc(cfg):
        raise OpenplcError("not an OpenPLC Modbus config: its bridge has no \"openplc\" object")
    items = modbusmap.collect(cfg)
    problems = modbusmap.check(items)
    if problems:
        raise OpenplcError("; ".join(problems))
    base = DEFAULT_IEC_BASE if iec_base is None else iec_base
    names = _register_names(cfg, items, decls)
    groups = []
    for area, limit in (("I", modbusmap.MAX_READ_REGISTERS), ("Q", modbusmap.MAX_WRITE_REGISTERS)):
        current = None
        for first, count, cls in _units(items, area):
            if (current is None or first != current.first + current.count or cls != current.key
                    or current.count + count > limit):
                current = Group(area, cls, first, cls)
                groups.append(current)
            current.count += count
            # A value longer than one request (a long trouble code list) is cut.
            while current.count > limit:
                rest = current.count - limit
                current.count = limit
                current = Group(area, cls, current.first + limit, cls)
                current.count = rest
                groups.append(current)
    for g in groups:
        g.aliases = [names.get((g.area, reg), "") for reg in g.registers]
    header = [g for g in groups if g.key == "header"]
    ordered = header + [g for g in groups if g.area == "I"] + [g for g in groups if g.area == "Q" and g.key != "header"]
    where = {}
    nxt = {"I": base, "Q": base}
    for g in sorted(ordered, key=lambda g: (g.area, g.first)):
        g.iec_first = nxt[g.area]
        for k, reg in enumerate(g.registers):
            where[(g.area, reg)] = "%%%sW%d" % (g.area, g.iec_first + k)
        nxt[g.area] += g.count
    return ordered, where


def _register_names(cfg, items, decls):
    """{(area, register): alias}: the value a register carries, `<value>_w<n>`
    for later words of a wider value, the bridge block's name for its words."""
    names = {}
    for d in decls:
        loc = parse_location(d.get("location"))
        if loc is None:
            continue
        nbytes = 1 if loc.size == "X" else modbusmap.SIZE_BYTES[loc.size]
        first = loc.index // 2
        for k, reg in enumerate(range(first, (loc.index + nbytes + 1) // 2)):
            names.setdefault((loc.area, reg), d["name"] if k == 0 else "%s_w%d" % (d["name"], k))
    for it in items:
        if it.kind != "bridge":
            continue
        base = "cw_" + declare.identifier(it.name[len("bridge."):] if it.name.startswith("bridge.") else it.name)
        for k, reg in enumerate(range(it.loc.index // 2, (it.loc.index + it.nbytes + 1) // 2)):
            names.setdefault((it.loc.area, reg), base if k == 0 else "%s_w%d" % (base, k))
    return names


def request_count(groups):
    """Modbus requests per poll: one per group."""
    return len(groups)


def budget_warning(groups):
    n = request_count(groups)
    if n > REQUEST_BUDGET:
        return ("%d Modbus requests per poll (more than %d): the runtime's Modbus master may not keep up; "
                "pack the config (Pack for Modbus) or raise poll_ms" % (n, REQUEST_BUDGET))
    return None


# -- Remote device file --------------------------------------------------------

def remote_device(cfg, decls, iec_base=None):
    """The editor's remote device (devices/remote/<name>.json) as a dict."""
    s = settings(cfg)
    groups, _ = layout(cfg, decls, iec_base)
    io_groups = []
    for g in groups:
        name = "%s_%s_%d" % ("in" if g.area == "I" else "out", g.label, g.first)
        io_groups.append({
            "id": str(uuid.uuid5(_NS, "%s/%s" % (s["remote_device"], name))),
            "name": name,
            "functionCode": g.fc,
            "cycleTime": s["poll_ms"],
            "offset": str(g.first),
            "length": g.count,
            "errorHandling": "set-to-zero" if g.key in ("header", "bridge") and g.area == "I" else "keep-last-value",
            "ioPoints": [{
                "id": "%s_%d" % (name, k),
                "name": "%s_%d" % (name, k),
                "type": _FC_TYPE[g.fc],
                "iecLocation": "%%%sW%d" % (g.area, g.iec_first + k),
                "alias": alias,
            } for k, alias in enumerate(g.aliases)],
        })
    return {
        "name": s["remote_device"],
        "protocol": "modbus-tcp",
        "modbusTcpConfig": {
            "transport": "tcp",
            "host": HOST,
            "port": s["port"],
            "timeout": TIMEOUT_MS,
            "slaveId": s["unit_id"],
            "ioGroups": io_groups,
        },
    }


def remote_device_text(cfg, decls, iec_base=None):
    return json.dumps(remote_device(cfg, decls, iec_base), indent=2) + "\n"


def remote_device_path(project_dir, cfg):
    return os.path.join(project_dir, REMOTE_DIR, settings(cfg)["remote_device"] + ".json")


# -- Generated programs ----------------------------------------------------------

_IEC_SIZE = {"BOOL": "X", "SINT": "B", "USINT": "B", "BYTE": "B", "INT": "W", "UINT": "W", "WORD": "W",
             "DINT": "D", "UDINT": "D", "DWORD": "D", "REAL": "D", "LINT": "L", "ULINT": "L", "LWORD": "L",
             "LREAL": "L"}


def _raw(area, reg):
    return "%s%d" % ("i" if area == "I" else "q", reg)


def _hex(v):
    return "16#%04X" % v


def _in_expr(d, loc, iec):
    """ST expression of a declaration's value from the raw input words."""
    t = d["type"]
    reg = loc.index // 2
    w = _raw("I", reg)
    if loc.size == "X":
        bit = loc.bit + (8 if loc.index % 2 == 0 else 0)
        return "(%s AND %s) <> 0" % (w, _hex(1 << bit))
    if loc.size == "B":
        byte = "SHR(%s, 8)" % w if loc.index % 2 == 0 else "(%s AND 16#00FF)" % w
        return byte if t == "WORD" else "WORD_TO_%s(%s)" % (t, byte)
    if loc.size == "W":
        return w if t == "WORD" else "WORD_TO_%s(%s)" % (t, w)
    words = [_raw("I", reg + k) for k in range(2 if loc.size == "D" else 4)]
    if iec == "high_first":
        words.reverse()
    if loc.size == "D":
        dw = "(SHL(WORD_TO_DWORD(%s), 16) OR WORD_TO_DWORD(%s))" % (words[1], words[0])
        return {"DWORD": dw, "REAL": "CW_DWORD_TO_REAL(%s)" % dw}.get(t, "DWORD_TO_%s(%s)" % (t, dw))
    lw = " OR ".join("SHL(WORD_TO_LWORD(%s), %d)" % (words[k], 16 * k) if k else "WORD_TO_LWORD(%s)" % words[k]
                     for k in range(4))
    lw = "(%s)" % lw
    return {"LWORD": lw, "LREAL": "CW_LWORD_TO_LREAL(%s)" % lw}.get(t, "LWORD_TO_%s(%s)" % (t, lw))


def _out_parts(d, loc, iec, temps):
    """[(register, ST word expression)] of a declaration's output value. A
    32- or 64-bit value is converted once into a temporary (`temps` gets
    (name, type, expression))."""
    t = d["type"]
    v = "%s.%s" % (LIST_NAME, d["name"])
    reg = loc.index // 2
    high = loc.index % 2 == 0
    if loc.size == "X":
        bit = loc.bit + (8 if high else 0)
        return [(reg, "SHL(BOOL_TO_WORD(%s), %d)" % (v, bit) if bit else "BOOL_TO_WORD(%s)" % v)]
    if loc.size == "B":
        word = v if t == "WORD" else "%s_TO_WORD(%s)" % (t, v)
        word = "(%s AND 16#00FF)" % word
        return [(reg, "SHL(%s, 8)" % word if high else word)]
    if loc.size == "W":
        return [(reg, v if t == "WORD" else "%s_TO_WORD(%s)" % (t, v))]
    n = 2 if loc.size == "D" else 4
    if loc.size == "D":
        whole = {"DWORD": v, "REAL": "CW_REAL_TO_DWORD(%s)" % v}.get(t, "%s_TO_DWORD(%s)" % (t, v))
        temp, to_word = "d%d" % reg, "DWORD_TO_WORD"
        temps.append((temp, "DWORD", whole))
    else:
        whole = {"LWORD": v, "LREAL": "CW_LREAL_TO_LWORD(%s)" % v}.get(t, "%s_TO_LWORD(%s)" % (t, v))
        temp, to_word = "l%d" % reg, "LWORD_TO_WORD"
        temps.append((temp, "LWORD", whole))
    parts = []
    for k in range(n):
        word = "%s(SHR(%s, %d))" % (to_word, temp, 16 * k) if k else "%s(%s)" % (to_word, temp)
        pos = k if iec == "low_first" else n - 1 - k
        parts.append((reg + pos, word))
    return parts


def _typed(decls):
    """The declarations the list carries: located, with a type the
    conversion knows, unique names."""
    out = []
    seen = {"ok", "link"}
    for d in decls:
        loc = parse_location(d.get("location"))
        if loc is None or loc.area not in "IQ" or _IEC_SIZE.get(d.get("type")) is None:
            continue
        if _IEC_SIZE[d["type"]] != loc.size and not (loc.size == "B" and d["type"] == "WORD"):
            continue
        if d["name"].lower() in seen:
            continue
        seen.add(d["name"].lower())
        out.append((d, loc))
    return out


def _block_starts(cfg):
    """{block name: (first register, word count)} of the bridge's blocks, and
    the live lists as [(network index, first register)]."""
    b = cfg["bridge"]
    out = {}
    for key, name, nbytes in (("control_location", "ctl", 6),):
        loc = parse_location(b.get(key))
        if loc is not None:
            out[name] = loc.index // 2
    sdo = b.get("sdo_bridge_location")
    if isinstance(sdo, dict):
        for key, name in (("request", "sdo_req"), ("response", "sdo_rsp")):
            loc = parse_location(sdo.get(key))
            if loc is not None:
                out[name] = loc.index // 2
    nets = [n.get("name") for n in cfg.get("networks") or [] if isinstance(n, dict)]
    live = []
    for entry in b.get("live_lists") or []:
        loc = parse_location(entry.get("location")) if isinstance(entry, dict) else None
        if loc is not None and entry.get("network") in nets:
            live.append((nets.index(entry["network"]), loc.index // 2))
    return out, live


def _raw_block(area, where, regs, notes):
    decls = [{"name": _raw(area, r), "type": "WORD", "location": where[(area, r)],
              "description": notes.get(r, "")} for r in regs]
    return declare.editor_block(decls)


def programs(cfg, decls, iec_base=None):
    """(canworks_in.st, canworks_out.st) texts in the editor's program form."""
    s = settings(cfg)
    groups, where = layout(cfg, decls, iec_base)
    iec = modbusmap.word_order_of(cfg)
    h = modbusmap.map_hash(cfg)
    typed = _typed(decls)
    blocks, live = _block_starts(cfg)
    in_regs = sorted(r for (a, r) in where if a == "I")
    out_regs = sorted(r for (a, r) in where if a == "Q")
    names = {}
    for g in groups:
        for reg, alias in zip(g.registers, g.aliases):
            names[(g.area, reg)] = alias
    stale_ms = max(300, 3 * s["watchdog_ms"])

    body = [GENERATED]
    body.append("moved := %s <> last_counter;" % _raw("I", 2 + STATUS_COUNTER_WORD))
    body.append("last_counter := %s;" % _raw("I", 2 + STATUS_COUNTER_WORD))
    body.append("stale(IN := NOT moved, PT := T#%dms);" % stale_ms)
    body.append("%s.ok := %s = %s AND %s = %s AND NOT stale.Q;"
                % (LIST_NAME, _raw("I", 0), _hex(h >> 16), _raw("I", 1), _hex(h & 0xFFFF)))
    flags = (2 if "ctl" in blocks else 0) | (4 if "sdo_req" in blocks and "sdo_rsp" in blocks else 0)
    for net, _ in live:
        if net < LINK_NETWORKS:
            flags |= 1 << (8 + net)
    body.append("%s.link[%d] := %s OR BOOL_TO_WORD(%s.ok);" % (LIST_NAME, LINK_FLAGS, _hex(flags), LIST_NAME))
    for k in range(4):
        body.append("%s.link[%d] := %s;" % (LIST_NAME, LINK_STATUS + k, _raw("I", 2 + k)))
    if "sdo_rsp" in blocks:
        for k in range(7):
            body.append("%s.link[%d] := %s;" % (LIST_NAME, LINK_SDO_RSP + k, _raw("I", blocks["sdo_rsp"] + k)))
    for net, first in live:
        if net >= LINK_NETWORKS:
            continue
        for k in range(LINK_LIVE_WORDS):
            body.append("%s.link[%d] := %s;" % (LIST_NAME, LINK_LIVE + net * LINK_LIVE_WORDS + k,
                                                _raw("I", first + k)))
    for d, loc in typed:
        if loc.area == "I":
            body.append("%s.%s := %s;" % (LIST_NAME, d["name"], _in_expr(d, loc, iec)))
    in_vars = (_raw_block("I", where, in_regs, {r: names.get(("I", r), "") for r in in_regs}) + "\n" +
               declare.editor_block([{"name": "last_counter", "type": "WORD"},
                                     {"name": "moved", "type": "BOOL"},
                                     {"name": "stale", "type": "TON"}]))
    in_st = "PROGRAM %s\n%s\n\n%s\n\nEND_PROGRAM" % (IN_PROGRAM, in_vars, "\n".join(body))

    parts = {}
    temps = []
    for d, loc in typed:
        if loc.area == "Q":
            for reg, expr in _out_parts(d, loc, iec, temps):
                parts.setdefault(reg, []).append(expr)
    if "ctl" in blocks:
        for k in range(3):
            parts.setdefault(blocks["ctl"] + k, []).append("%s.link[%d]" % (LIST_NAME, LINK_CTL + k))
    if "sdo_req" in blocks:
        for k in range(7):
            parts.setdefault(blocks["sdo_req"] + k, []).append("%s.link[%d]" % (LIST_NAME, LINK_SDO_REQ + k))
    body = [GENERATED]
    body += ["%s := %s;" % (name, expr) for name, _, expr in temps]
    for reg in out_regs:
        if reg < 3:
            continue
        exprs = parts.get(reg) or ["0"]
        body.append("%s := %s;" % (_raw("Q", reg), " OR ".join(exprs)))
    body.append("(* PLC link header, last: running, then the map hash 0x%08x *)" % h)
    body.append("%s := %s;" % (_raw("Q", 1), _hex(h >> 16)))
    body.append("%s := %s;" % (_raw("Q", 2), _hex(h & 0xFFFF)))
    body.append("%s := 1;" % _raw("Q", 0))
    out_vars = _raw_block("Q", where, out_regs, {r: names.get(("Q", r), "") for r in out_regs})
    if temps:
        out_vars += "\n" + declare.editor_block([{"name": name, "type": type_} for name, type_, _ in temps])
    out_st = "PROGRAM %s\n%s\n\n%s\n\nEND_PROGRAM" % (OUT_PROGRAM, out_vars, "\n".join(body))
    return in_st, out_st


def global_list(decls):
    """The `canworks` global variable list in project.json's form."""
    def var(name, type_, doc):
        return {"name": name, "class": "global", "type": {"definition": "base-type", "value": type_},
                "location": "", "documentation": doc}
    link = {"name": "link", "class": "global",
            "type": {"definition": "array", "value": "ARRAY[0..%d] OF WORD" % (LINK_WORDS - 1),
                     "data": {"baseType": {"definition": "base-type", "value": "WORD"},
                              "dimensions": [{"dimension": "0..%d" % (LINK_WORDS - 1)}]}},
            "location": "", "documentation": "the bridge's control, SDO and live list words: the canworks blocks' LINK"}
    variables = [var("ok", "BOOL", "canworks-bridge answers and serves this program's map"), link]
    for d, loc in _typed(decls):
        variables.append(var(d["name"], d["type"], declare.comment_text(d.get("description") or "")))
    return {"name": LIST_NAME, "variables": variables,
            "documentation": "canworks values; generated, Update declarations rewrites it"}


# -- Writing into an editor project -------------------------------------------------

# What canworks last wrote into the project: {relative path: sha256}, so a
# file someone else changed is replaced only after a confirm.
STAMP = os.path.join("canworks", ".openplc-files.json")


class ChangedFiles(Exception):
    """Files canworks writes were changed by someone else since it wrote them."""

    def __init__(self, files):
        super().__init__("changed outside canworks: " + ", ".join(files))
        self.files = files


def own_files(cfg):
    """The project files canworks writes, relative, with /."""
    return ["devices/remote/%s.json" % settings(cfg)["remote_device"],
            "pous/programs/%s.st" % IN_PROGRAM, "pous/programs/%s.st" % OUT_PROGRAM]


def free_iec_base(cfg, decls, uses):
    """The lowest %IW/%QW index from 100 on where every point of the remote
    device fits without a location another part of the project uses (scan
    uses, canworks' own files left out)."""
    groups, _ = layout(cfg, decls, 0)
    n = {"I": sum(g.count for g in groups if g.area == "I"), "Q": sum(g.count for g in groups if g.area == "Q")}
    mine = set(own_files(cfg))
    taken = {(u.loc.area, u.loc.element) for u in uses
             if u.loc.size == "W" and u.loc.area in "IQ" and u.file not in mine}
    base = DEFAULT_IEC_BASE
    while any((a, base + k) in taken for a in "IQ" for k in range(n[a])):
        base += 1
    return base


def _sha(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def _stamps(project_dir):
    try:
        with open(os.path.join(project_dir, STAMP), encoding="utf-8") as f:
            doc = json.load(f)
        return doc if isinstance(doc, dict) else {}
    except (OSError, ValueError):
        return {}


def changed_files(project_dir, cfg, texts):
    """Own files that exist, are not what canworks last wrote there and are
    not what it would write now."""
    stamps = _stamps(project_dir)
    out = []
    for rel in own_files(cfg):
        path = os.path.join(project_dir, *rel.split("/"))
        if not os.path.isfile(path):
            continue
        sha = _sha(path)
        if sha != stamps.get(rel) and sha != hashlib.sha256(texts[rel].encode("utf-8")).hexdigest():
            out.append(rel)
    return out


def sync_project(project_dir, cfg, decls, uses=(), force=False):
    """Writes the remote device, canworks_in, canworks_out and the list and
    instances in project.json for an openplc config. Raises ChangedFiles
    unless `force` when one of canworks' files was changed by someone else.
    Returns {written, iec_base, requests, warning}."""
    base = settings(cfg)["iec_base"]
    if base is None:
        base = free_iec_base(cfg, decls, uses)
    in_st, out_st = programs(cfg, decls, base)
    rel = own_files(cfg)
    texts = {rel[0]: remote_device_text(cfg, decls, base), rel[1]: in_st, rel[2]: out_st}
    changed = changed_files(project_dir, cfg, texts)
    if changed and not force:
        raise ChangedFiles(changed)
    written = []
    stamps = _stamps(project_dir)
    for r in rel:
        path = os.path.join(project_dir, *r.split("/"))
        os.makedirs(os.path.dirname(path), exist_ok=True)
        _write(path, texts[r])
        stamps[r] = hashlib.sha256(texts[r].encode("utf-8")).hexdigest()
        written.append(path)
    pj = os.path.join(project_dir, "project.json")
    with open(pj, encoding="utf-8") as f:
        doc = json.load(f)
    if not isinstance(doc, dict) or not isinstance(doc.get("data"), dict):
        raise OpenplcError("%s has no \"data\" object" % pj)
    doc["data"] = project_data(doc["data"], decls)
    _write(pj, json.dumps(doc, indent=2))
    written.append(pj)
    stamp = os.path.join(project_dir, STAMP)
    os.makedirs(os.path.dirname(stamp), exist_ok=True)
    _write(stamp, json.dumps(stamps, indent=2, sort_keys=True) + "\n")
    groups, _ = layout(cfg, decls, base)
    return {"written": written, "iec_base": base, "requests": request_count(groups),
            "warning": budget_warning(groups)}


def instances(resource):
    """`resource` (project.json data.configuration.resource) with canworks_in
    first and canworks_out last in the first task; returns the new instance
    list."""
    tasks = resource.get("tasks") or []
    task = tasks[0]["name"] if tasks and isinstance(tasks[0], dict) else None
    old = [i for i in resource.get("instances") or []
           if not (isinstance(i, dict) and i.get("program") in (IN_PROGRAM, OUT_PROGRAM))]
    mine = lambda program: {"name": program + "_instance", "task": task, "program": program}
    return [mine(IN_PROGRAM)] + old + [mine(OUT_PROGRAM)]


def project_data(data, decls):
    """project.json `data` with the canworks list and instances in place."""
    data = dict(data)
    lists = [l for l in data.get("globalVariableLists") or []
             if not (isinstance(l, dict) and l.get("name") == LIST_NAME)]
    data["globalVariableLists"] = lists + [global_list(decls)]
    conf = dict(data.get("configuration") or {})
    resource = dict(conf.get("resource") or {})
    resource["instances"] = instances(resource)
    conf["resource"] = resource
    data["configuration"] = conf
    return data


def _write(path, text):
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    replace_file(tmp, path)
